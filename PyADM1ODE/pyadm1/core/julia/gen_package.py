"""Generate the precompiled Julia package ``PyADM1Julia`` from ``adm1da.jl``.

Why a package: Julia only writes cached *native* code for packages. The ADM1
port used to be a source string evaluated at runtime, so every process paid
~5.7 s of JIT before the first step. Turning it into a package lets
``PrecompileTools`` bake the specialisations into the pkgimage.

Run this after changing ``adm1da.jl`` or ``PARAM_FIELDS``:

    .venv\\Scripts\\python.exe pyadm1/core/julia/gen_package.py

It rewrites ``PyADM1Julia/src/{PyADM1Julia,fields,workload_data}.jl``.
"""

from __future__ import annotations

import inspect
from pathlib import Path

import numpy as np

HERE = Path(__file__).resolve().parent
PKG = HERE / "PyADM1Julia"
SRC = HERE / "adm1da.jl"

WORKLOAD = '''
# ---------------------------------------------------------------------------
# Precompile workload
#
# Julia caches native code per concrete argument type. Running one real
# integration at package-precompile time therefore removes the first-call JIT
# that used to cost ~5.7 s per process. The numbers below are a default plant's
# parameter vector and state, generated by gen_package.py.
# ---------------------------------------------------------------------------

@compile_workload begin
    pvec = copy(W_PVEC)
    u0 = copy(W_U0)
    # Call the typed cores, not the AbstractVector wrappers: the cores are the
    # expensive part, and they are the exact methods the runtime hits after the
    # PyArray -> Vector conversion.
    _rhs_eval(pvec, u0)
    _q_s_loss_eval(pvec, u0)
    _integrate_step(pvec, u0, 0.0, 1.0e-3, 1.0e-6, 1.0e-8, 1.0e-3)
    _integrate_trace(pvec, u0, 0.0, 1.0e-3, 1.0e-6, 1.0e-8, 1.0e-3)
end
'''


def julia_array(name: str, values) -> str:
    body = ", ".join(f"{float(v):.17g}" for v in values)
    return f"const {name} = Float64[{body}]\n"


def main() -> int:
    from pyadm1 import BiogasPlant, Feedstock
    from pyadm1.configurator.plant_configurator import PlantConfigurator
    from pyadm1.core import adm1_julia

    fs = Feedstock(
        ["maize_silage_milk_ripeness", "swine_manure"],
        feeding_freq=24,
        total_simtime=6.0,
    )
    plant = BiogasPlant("gen-package")
    PlantConfigurator(plant, fs).add_digester(
        digester_id="main_digester",
        V_liq=1050.0,
        V_gas=150.0,
        T_ad=42.0 + 273.15,
        Q_substrates=[11.4, 6.1],
        k_L_a=200.0,
    )
    plant.initialize()
    adm1 = plant.components["main_digester"].adm1

    kwargs = {}
    if len(inspect.signature(adm1_julia.build_param_vector).parameters) > 1:
        kwargs["q_substrates"] = [11.4, 6.1]
    pvec = np.asarray(adm1_julia.build_param_vector(adm1, **kwargs), dtype=float)
    u0 = np.asarray(plant.components["main_digester"].adm1_state, dtype=float)

    if pvec.size != len(adm1_julia.PARAM_FIELDS) + 37:
        raise SystemExit(f"unexpected pvec length {pvec.size}")
    if u0.size != 41:
        raise SystemExit(f"unexpected state length {u0.size}")

    PKG.mkdir(parents=True, exist_ok=True)
    (PKG / "src").mkdir(parents=True, exist_ok=True)

    # --- fields.jl: the authoritative field order, frozen into the package ---
    fields = ", ".join(f":{name}" for name in adm1_julia.PARAM_FIELDS)
    (PKG / "src" / "fields.jl").write_text(
        "# Generated by gen_package.py - do not edit.\n"
        "# Mirrors pyadm1.core.adm1_julia.PARAM_FIELDS; the bridge asserts they match.\n"
        f"const PFIELDS = ({fields},)\n",
        encoding="utf-8",
    )

    # --- workload_data.jl ---------------------------------------------------
    (PKG / "src" / "workload_data.jl").write_text(
        "# Generated by gen_package.py - a default plant's inputs, used only to\n"
        "# warm the compiler during precompilation.\n"
        + julia_array("W_PVEC", pvec)
        + julia_array("W_U0", u0),
        encoding="utf-8",
    )

    # --- PyADM1Julia.jl: adm1da.jl with the placeholder swapped out ---------
    source = SRC.read_text(encoding="utf-8")
    if "__PARAM_FIELDS__" not in source:
        raise SystemExit(f"{SRC} has no __PARAM_FIELDS__ placeholder")

    source = source.replace(
        "const PFIELDS = __PARAM_FIELDS__",
        'include("fields.jl")\ninclude("workload_data.jl")',
    )
    source = source.replace(
        "using SciMLBase: SciMLBase, ODEProblem, solve",
        "using SciMLBase: SciMLBase, ODEProblem, solve\nusing PrecompileTools: @compile_workload",
    )
    source = source.replace("end # module", WORKLOAD + "\nend # module")

    header = (
        "# PyADM1Julia - ADM1da right-hand side as a precompilable package.\n"
        "#\n"
        "# Generated from pyadm1/core/julia/adm1da.jl by gen_package.py. Edit the\n"
        "# source there and re-run the generator; do not edit this copy.\n"
    )
    # drop the original file header comment block, keep from `module` on
    module_at = source.index("module PyADM1Julia")
    source = header + "\n" + source[module_at:]
    (PKG / "src" / "PyADM1Julia.jl").write_text(source, encoding="utf-8")

    (PKG / "Project.toml").write_text(
        'name = "PyADM1Julia"\n'
        'uuid = "3f5b0c62-7f7d-4a1e-9d0e-6b1f2c3a4d5e"\n'
        'version = "0.1.0"\n'
        "\n"
        "[deps]\n"
        'OrdinaryDiffEqRosenbrock = "43230ef6-c299-4910-a778-202eb28ce4ce"\n'
        'PrecompileTools = "aea7be01-6a6a-4083-8856-8a6e6704d82a"\n'
        'SciMLBase = "0bca4576-84f4-4d90-8ffe-ffa030f20462"\n'
        "\n"
        "[compat]\n"
        "julia = \"1.9\"\n",
        encoding="utf-8",
    )
    print(f"wrote {PKG}")
    print(f"  PFIELDS  : {len(adm1_julia.PARAM_FIELDS)}")
    print(f"  pvec     : {pvec.size}")
    print(f"  u0       : {u0.size}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
